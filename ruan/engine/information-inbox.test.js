import assert from "node:assert/strict";
import { createInformationInbox, INFORMATION_INBOX_STORAGE_KEY } from "./information-inbox.js";
function createStorage(){const data=new Map();return{getItem:key=>data.has(key)?data.get(key):null,setItem:(key,value)=>data.set(key,String(value)),removeItem:key=>data.delete(key)};}
let id=0;
const storage=createStorage();
const inbox=createInformationInbox({storage,now:()=>"2026-10-16T10:00:00.000Z",idFactory:()=>"info-"+(++id),eventTarget:null});
const received=inbox.receiveInformation({sender:"Pessoal",category:"Alerta",title:"Conta vence hoje",message:"Conferir pagamento",sourceId:"bill-1"});
assert.equal(received.id,"info-1");
assert.equal(inbox.list().length,1);
assert.equal(inbox.list()[0].sender,"Pessoal");
assert.equal(inbox.receiveInformation({sender:"Pessoal",category:"Alerta",title:"Conta duplicada",message:"Duplicada",sourceId:"bill-1"}).id,"info-1","sourceId deve impedir duplicação da mesma origem");
assert.equal(inbox.markRead("info-1").read,true);
assert.equal(JSON.parse(storage.getItem(INFORMATION_INBOX_STORAGE_KEY)).length,1);
const exported=inbox.exportData();
assert.equal(exported.schema,"darkhub-information-v1");
const second=createInformationInbox({storage:createStorage(),now:()=>"2026-10-16T11:00:00.000Z",idFactory:()=>"other-"+(++id),eventTarget:null});
assert.equal(second.importData(exported).length,1);
assert.throws(()=>inbox.receiveInformation({sender:"Pessoal",message:"Sem título"}),/Título é obrigatório/);
assert.equal(inbox.deleteInformation("info-1"),true);
assert.equal(inbox.list().length,0);
console.log("darkHub information inbox tests passed.");
