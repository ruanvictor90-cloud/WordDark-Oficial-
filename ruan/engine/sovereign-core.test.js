import assert from "node:assert/strict";
import { createRuanSovereignCore } from "./sovereign-core.js";
let n = 0;
const core = createRuanSovereignCore({ now: () => "2026-10-12T00:00:00.000Z", idFactory: () => "req-" + (++n) });
let received = null;
const peer = core.connectPeer("worddark", { receiveFromRuan: payload => { received = payload; return { accepted: true }; } });
const request = peer.submitRequest({ capability: "calendar.read-summary", purpose: "Prepare a personal agenda summary", payload: { range: "today" } });
assert.equal(request.status, "PENDING_OWNER_DECISION");
assert.equal(peer.status().role, "REQUEST_ONLY");
assert.equal(typeof peer.approveRequest, "undefined");
assert.equal(typeof peer.writePersonalState, "undefined");
assert.equal(core.owner.status().externalWriteAccess, false);
assert.equal(core.owner.listRequests({ status: "PENDING_OWNER_DECISION" }).length, 1);
assert.equal(core.owner.decideRequest(request.requestId, { decision: "DENY", reason: "Not authorized" }).status, "DENIED");
assert.throws(() => core.owner.decideRequest(request.requestId, { decision: "APPROVE" }), /já decidida/);
const delivery = core.owner.sendToPeer("worddark", { type: "RuanMessage", body: "Prepare a draft, do not execute." });
assert.equal(delivery.delivered, true);
assert.deepEqual(received, { type: "RuanMessage", body: "Prepare a draft, do not execute." });
assert.throws(() => core.owner.sendToPeer("unknown", {}), /não conectado/);
console.log("Ruan sovereign core tests passed.");
