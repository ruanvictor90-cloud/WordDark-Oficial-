import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = path => readFileSync(new URL(path, import.meta.url), "utf8");
const html = read("./index.html");
const script = read("./ruan-hub.js");
const css = read("./ruan-hub.css");
const inbox = read("./engine/information-inbox.js");
const apk = read("../.github/workflows/darkhub-apk.yml");
const doc = read("../DARKHUB-CENTRAL.md");
assert.ok(html.includes('id="panel-workspace"') && html.includes('id="information-form"'), "darkHub must expose an information inbox");
assert.ok(html.includes('id="package-workspace"') && html.includes("actions/workflows/darkhub-apk.yml"), "darkHub must expose the APK packager");
assert.ok(script.includes("createInformationInbox") && script.includes("window.DarkHubInbox"), "apps need a defined information-receiving API");
assert.ok(script.includes("informationImportFile") && script.includes("darkhub:inbox-changed"), "inbox must support import and cross-app updates");
assert.ok(inbox.includes('darkhub-information-v1') && inbox.includes("receiveInformation"), "inbox contract must be versioned and callable");
assert.ok(css.includes(".information-card") && css.includes(".package-workspace"), "inbox and packager must have interface styles");
assert.ok(apk.includes("workflow_dispatch:") && apk.includes("assembleDebug") && apk.includes("app-debug.apk"), "APK workflow must support manual build and publish artifact");
assert.ok(apk.includes("source_path") && apk.includes("app_id"), "APK workflow must accept the app source and Android identity");
assert.ok(doc.includes("não sincroniza entre aparelhos") && doc.includes("darkhub-information-v1"), "integration limits and contract must be documented");
console.log("darkHub central structure tests passed.");
