import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const root = new URL('./', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const html = read('index.html');
assert.ok(html.includes('RUAN · CENTRAL'));
assert.ok(!html.includes('Informações'));
assert.ok(!html.includes('info-grid'));
assert.ok(!html.includes('carousel-phrase'));
assert.ok(html.includes('id="finance-widget-value"'));
assert.ok(html.includes('id="tasks-widget-value"'));
assert.ok(html.includes('class="ruan-info-widgets"'));
assert.equal((html.match(/class="ruan-info-widgets"/g) || []).length, 1, 'Central must contain exactly one summary widget section');
assert.equal((html.match(/id="finance-widget-value"/g) || []).length, 1, 'Finance summary ID must be unique');
assert.equal((html.match(/id="tasks-widget-value"/g) || []).length, 1, 'Task summary ID must be unique');
assert.ok(html.includes('class="ruan-home-grid"'));
assert.ok(html.includes('id="greeting"') && html.includes('id="greeting-phrase"'), 'Ruan home must include a time-based greeting and rotating phrase');
assert.ok(!html.includes('<small>Central pessoal</small>'), 'The brand must not show the extra Central subtitle');
assert.ok(read('app.css').includes('min-height:96px;max-height:118px'), 'Ruan apps must be compact and near the top');
assert.ok(read('app.css').includes('body.ruan-launcher .ruan-info-widgets{display:grid'), 'Central must show two compact personal summary widgets');
assert.ok(read('app.css').includes('--bg:#09070f;--panel:#15111f'), 'Ruan must retain the black/purple identity');
assert.ok(read('app.css').includes('#392052'), 'Ruan background must not revert to the old blue palette');
assert.ok(read('app.js').includes('function renderWidgets()'), 'Central widgets must refresh from personal local records');
assert.ok(read('app.js').includes('function toggleApps()'), 'The global app drawer must open and close');
assert.ok(read('app.js').includes('function rotatePhrase()'), 'The greeting phrase carousel must rotate');
assert.ok(read('app.css').includes('body.ruan-launcher .apps-drawer{display:block'), 'The drawer must be visible when not hidden');
assert.ok(html.includes('id="apps-drawer"'), 'The Ruan central must contain the global app drawer');
assert.ok(html.includes('id="apps-toggle"'), 'The global app drawer must have a working toggle');
assert.ok(html.includes('class="home-app-name">Pessoal</span>'));
assert.ok(html.includes('class="home-app-name">Shadow</span>'));
assert.ok(html.includes('class="home-app-name">WordDark Hub</span>'));
assert.ok(html.includes('./apps/pessoal/index.html'));
assert.ok(html.includes('./apps/shadow/index.html'));
assert.ok(html.includes('href="../hub/index.html"'));
assert.ok(html.includes('WordDark Hub'));
assert.ok(read('engine/notifications.js').includes('ruan.important.notifications.v1'));
assert.ok(read('apps/pessoal/tarefas.js').includes('Tarefa com prazo registrada'));
assert.ok(read('apps/pessoal/financeiro.js').includes('Conta a pagar registrada'));
assert.ok(read('app.js').includes('ruan.important.notifications.v1'), 'Ruan central must aggregate important app alerts');
assert.ok(read('app.css').includes('body.ruan-launcher .top-actions{display:flex!important'), 'Ruan home must keep its notification bell visible');
assert.ok(html.includes('app.css?v=20261016-final-2') && html.includes('app.js?v=20261016-final-2'), 'Ruan home must request refreshed assets');
assert.ok(!html.includes('Área ADM'));
assert.ok(existsSync(new URL('engine/central-engine.js', root)));
assert.ok(existsSync(new URL('apps/pessoal/financeiro.html', root)));
assert.ok(existsSync(new URL('apps/pessoal/tarefas.html', root)));
assert.ok(existsSync(new URL('apps/shadow/darkeye/index.html', root)));
const pessoal = read('apps/pessoal/index.html');
assert.ok(!pessoal.includes('apps-drawer'));
assert.ok(!pessoal.includes('apps-toggle'));
assert.ok(!pessoal.includes('apps/shadow'));
assert.ok(pessoal.includes('class="pessoal-app-grid"'));
assert.ok(read('apps/pessoal/pessoal.css').includes('min-height:94px;max-height:112px'), 'Pessoal apps must follow the same compact launcher architecture');
assert.ok(pessoal.includes('class="pessoal-app-name">Financeiro</span>'));
assert.ok(pessoal.includes('class="pessoal-app-name">Tarefas</span>'));
assert.ok(pessoal.includes('circle cx="41" cy="37" r="7"'), 'Financeiro must use its dedicated money icon');
assert.ok(pessoal.includes('M21 36l3 3 5-6'), 'Tarefas must use a distinct checklist icon');
assert.ok(pessoal.includes('href="./financeiro.html"'));
assert.ok(pessoal.includes('href="./tarefas.html"'));
const pessoalScript = read('apps/pessoal/app.js');
assert.ok(!pessoalScript.includes('apps-drawer'));
assert.ok(!pessoalScript.includes('apps-toggle'));
const shadow = read('apps/shadow/index.html');
assert.ok(!shadow.includes('apps/shadow/index.html'));
assert.ok(shadow.includes('class="shadow-card"'));
assert.ok(shadow.includes('href="./darkeye/index.html"'));
assert.ok(shadow.includes('circle cx="27" cy="27" r="7"'), 'DarkEye launcher must use the refined lens icon');
assert.ok(shadow.includes('href="./darkeye/index.html"'));
const finance = read('apps/pessoal/financeiro.html');
const tasks = read('apps/pessoal/tarefas.html');
const browser = read('apps/shadow/darkeye/index.html');
assert.ok(finance.includes('finance-form'));
assert.ok(tasks.includes('task-form'));
assert.ok(browser.includes('DarkEye'));
assert.ok(browser.includes('web-preview'));
assert.ok(!browser.includes('class="area-nav"'));
const appPagesWithoutDuplicateNav = [finance, tasks, browser];
for (const page of appPagesWithoutDuplicateNav) {
  assert.equal((page.match(/<nav class="area-nav"/g) || []).length, 0, 'Individual app pages must not repeat the area navigation row');
}
assert.ok(finance.includes('class="back-button"') && tasks.includes('class="back-button"') && browser.includes('class="back-button"'), 'Individual app pages must keep their return arrows');
const serviceWorker = read('sw.js');
assert.ok(serviceWorker.includes("const CACHE='ruan-central-v25'"));
assert.ok(serviceWorker.includes('caches.match(event.request,{ignoreSearch:true})'), 'Offline cache must serve versioned CSS/JS URLs from the core cache');
assert.ok(read('apps/pessoal/app.js').includes('const localDateKey='), 'Pessoal dashboard must use local calendar dates for deadlines');
assert.ok(read('apps/pessoal/financeiro.js').includes('const localDateKey='), 'Finance dates must use the device local calendar');
assert.ok(read('apps/pessoal/tarefas.js').includes('const localDateKey='), 'Task deadlines must use the device local calendar');
assert.ok(!read('apps/pessoal/financeiro.js').includes('new Date().toISOString().slice(0,10)'), 'Finance form must not derive local today from UTC');
assert.ok(!read('apps/pessoal/tarefas.js').includes('new Date().toISOString().slice(0,10)'), 'Task deadline summary must not derive local today from UTC');
assert.ok(!read('apps/pessoal/app.js').includes('new Date().toISOString().slice(0,10)'), 'Dashboard must not derive local today from UTC');
console.log('Ruan app structure tests passed.');
