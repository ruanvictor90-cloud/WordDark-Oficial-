import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const root = new URL('./', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8');
const html = read('index.html');
assert.ok(html.includes('RUAN · CENTRAL'));
assert.ok(html.includes('Informações'));
assert.ok(html.includes('apps-drawer'));
assert.ok(html.includes('./apps/pessoal/index.html'));
assert.ok(html.includes('./apps/shadow/index.html'));
assert.ok(!html.includes('Área ADM'));
assert.ok(existsSync(new URL('engine/central-engine.js', root)));
assert.ok(existsSync(new URL('apps/pessoal/financeiro.html', root)));
assert.ok(existsSync(new URL('apps/pessoal/tarefas.html', root)));
assert.ok(existsSync(new URL('apps/shadow/darkeye/index.html', root)));
const pessoal = read('apps/pessoal/index.html');
assert.ok(!pessoal.includes('apps-drawer'));
assert.ok(!pessoal.includes('apps-toggle'));
assert.ok(!pessoal.includes('apps/shadow'));
const pessoalScript = read('apps/pessoal/app.js');
assert.ok(!pessoalScript.includes('apps-drawer'));
assert.ok(!pessoalScript.includes('apps-toggle'));
const shadow = read('apps/shadow/index.html');
assert.ok(!shadow.includes('apps/shadow/index.html'));
const finance = read('apps/pessoal/financeiro.html');
const tasks = read('apps/pessoal/tarefas.html');
const browser = read('apps/shadow/darkeye/index.html');
assert.ok(finance.includes('finance-form'));
assert.ok(tasks.includes('task-form'));
assert.ok(browser.includes('DarkEye'));
assert.ok(browser.includes('web-preview'));
console.log('Ruan app structure tests passed.');
