import assert from "node:assert/strict";
import {createDarkHubOrchestrator,ORCHESTRATOR_SCHEMA} from "./orchestrator.js";
function memoryStorage(){const map=new Map();return {getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,value)};}
const storage=memoryStorage();let n=0;const now=()=> "2026-10-17T00:00:00.000Z",idFactory=()=> "orch-"+(++n);
const hub=createDarkHubOrchestrator({storage,now,idFactory});
assert.equal(hub.schema,ORCHESTRATOR_SCHEMA);
assert.equal(hub.dashboard().apps,2);
assert.throws(()=>hub.registerCapability({appId:"unknown",id:"demo.cap",name:"Demo",description:"demo"}),/registrado/);
const cap=hub.registerCapability({appId:"shadoweb",id:"browser.open",name:"Abrir página",description:"Abrir uma página em uma aba",permission:"local-only"});
assert.equal(cap.status,"registered");
assert.throws(()=>hub.createTask({appId:"shadoweb",title:"Abrir página",capabilityId:cap.fullId}),/habilitada/);
hub.setCapabilityStatus(cap.fullId,"enabled");
const task=hub.createTask({appId:"shadoweb",title:"Validar favoritos",capabilityId:cap.fullId,priority:"high"});
assert.equal(task.state,"queued");
assert.equal(hub.dashboard().queuedTasks,1);
assert.throws(()=>hub.transitionTask(task.id,"done"),/Transição não permitida/);
hub.transitionTask(task.id,"assigned");
hub.transitionTask(task.id,"running");
hub.transitionTask(task.id,"done",{result:"Validado manualmente"});
assert.equal(hub.listTasks()[0].result,"Validado manualmente");
assert.equal(hub.dashboard().queuedTasks,0);
assert.equal(hub.dashboard().unreadMessages,4);
const blocked=hub.createTask({appId:"worddark-hub",title:"Preparar contrato de conexão"});
hub.transitionTask(blocked.id,"cancelled");
assert.equal(hub.dashboard().queuedTasks,0);
const backup=hub.exportState();
const restored=createDarkHubOrchestrator({storage:memoryStorage(),now,idFactory});
restored.importState(backup);
assert.equal(restored.listCapabilities().length,1);
assert.equal(restored.listTasks().length,2);
const external=hub.registerCapability({appId:"shadoweb",id:"remote.fetch",name:"Buscar serviço externo",description:"Acesso a um serviço remoto",permission:"external"});
assert.throws(()=>hub.setCapabilityStatus(external.fullId,"enabled"),/permissão aprovada/);
console.log("darkHub orchestrator tests passed");
