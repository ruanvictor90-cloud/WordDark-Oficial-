import assert from "node:assert/strict";
import {createDarkHubRuntime} from "./runtime.js";
import {createDarkHubWorkspace,WORKSPACE_SCHEMA} from "./workspace.js";
function memoryStorage(){const map=new Map();return {getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,value)};}
const storage=memoryStorage();let n=0;
const runtime=createDarkHubRuntime({storage,now:()=>"2026-10-18T00:00:00.000Z",idFactory:()=>"app-"+(++n),eventTarget:null});
const app=runtime.registerApp({id:"workspace-demo",name:"Projeto Demo",description:"Projeto de teste"});
const workspace=createDarkHubWorkspace({storage,now:()=>"2026-10-18T00:00:00.000Z",idFactory:()=>"file-"+(++n),runtime});
assert.equal(workspace.schema,WORKSPACE_SCHEMA);
assert.equal(workspace.listProjects().find(p=>p.appId===app.id).fileCount,0);
assert.equal(workspace.validateProject(app.id).valid,false);
assert.throws(()=>workspace.preparePackage(app.id),/não é possível preparar o pacote/i);
assert.throws(()=>workspace.createFile("missing","index.html",""),/registrado/);
assert.throws(()=>workspace.createFile(app.id,"../secret.js",""),/relativo/);
const envFile=workspace.createFile(app.id,".env","PLACEHOLDER=not-a-secret");
assert.ok(workspace.validateProject(app.id).warnings.some(w=>w.includes("segredos")));
workspace.deleteFile(app.id,envFile.path);
const workflowFile=workspace.createFile(app.id,".github/workflows/pages.yml","name: test");
assert.equal(workflowFile.path,".github/workflows/pages.yml");
workspace.deleteFile(app.id,workflowFile.path);
const file=workspace.createFile(app.id,"src/main.js","export const answer = 42;");
assert.equal(file.revision,1);
assert.throws(()=>workspace.createFile(app.id,"src/main.js","duplicado"),/Já existe/);
const saved=workspace.saveFile(app.id,"src/main.js","export const answer = 43;");
workspace.createFile(app.id,"src/other.js","");
assert.throws(()=>workspace.renameFile(app.id,"src/other.js","src/main.js"),/Já existe/);
workspace.deleteFile(app.id,"src/other.js");
assert.equal(workspace.renameFile(app.id,"src/main.js","src/renamed.js").path,"src/renamed.js");
assert.equal(workspace.renameFile(app.id,"src/renamed.js","src/main.js").path,"src/main.js");
assert.equal(saved.revision,2);
assert.equal(workspace.getFile(app.id,"src/main.js").content,"export const answer = 43;");
const snapshot=workspace.createSnapshot(app.id,"Versão antes de alteração");
workspace.saveFile(app.id,"src/main.js","export const answer = 44;");
assert.equal(workspace.listSnapshots(app.id)[0].id,snapshot.id);
workspace.restoreSnapshot(snapshot.id);
assert.equal(workspace.getFile(app.id,"src/main.js").content,"export const answer = 43;");
const validation=workspace.validateProject(app.id);
assert.equal(validation.valid,true);
assert.equal(validation.files,1);
const prepared=workspace.preparePackage(app.id,"Pacote de teste");
assert.equal(prepared.published,false);
assert.equal(prepared.validation.valid,true);
const bundle=workspace.exportProject(app.id);
const invalidBundle=JSON.parse(JSON.stringify(bundle));
if(invalidBundle.snapshots.length)invalidBundle.snapshots[0].files[0].content={invalid:true};
assert.throws(()=>workspace.importProject(invalidBundle),/Conteúdo inválido/);
const app2=runtime.registerApp({id:"workspace-copy",name:"Cópia Demo",description:"Projeto de importação"});
bundle.app.id=app2.id;bundle.project.appId=app2.id;bundle.project.files=bundle.project.files.map(f=>({...f}));
bundle.snapshots=bundle.snapshots.map(s=>({...s,appId:app2.id}));
assert.equal(workspace.importProject(bundle).fileCount,1);
assert.equal(workspace.getFile(app2.id,"src/main.js").content,"export const answer = 43;");
assert.throws(()=>workspace.saveFile(app.id,"missing.js","x"),/não encontrado/);
assert.equal(workspace.deleteFile(app2.id,"src/main.js"),true);
assert.equal(workspace.listFiles(app2.id).length,0);
console.log("darkHub workspace tests passed");
