const assert = require("node:assert/strict");
(async () => {
  const { createCommercialEngine } = await import("./commercial-engine.js");
  let n = 0;
  const engine = createCommercialEngine({ now: () => "2026-10-13T00:00:00.000Z", idFactory: () => String(++n) });
  assert.equal(engine.status().sectorId, "earth");
  engine.addCatalogItem({ itemId: "offer-1", name: "Pacote mensal", category: "conteúdo", price: 250, recurrence: "MONTHLY" });
  engine.createLead({ leadId: "lead-1", requesterId: "client-1", name: "Cliente teste", need: "Gerir canal", category: "channels", recurrence: "MONTHLY", sourceDemandId: "demand-1", businessContext: { source: "Terra" } });
  assert.equal(engine.getLead("lead-1").sourceDemandId, "demand-1");
  assert.equal(engine.getLead("lead-1").businessContext.source, "Terra");
  assert.equal(engine.qualifyLead("lead-1", "operator").status, "QUALIFIED");
  const proposal = engine.createProposal({ proposalId: "proposal-1", leadId: "lead-1", title: "Gestão mensal", scope: "Planejamento e relatório", amount: 250 });
  assert.equal(proposal.paymentEnabled, false);
  assert.throws(() => engine.openOrder("proposal-1"), /proposta aceita/);
  engine.decideProposal("proposal-1", "ACCEPTED", "client-1");
  const order = engine.openOrder("proposal-1");
  assert.equal(order.sectorId, "earth");
  assert.equal(order.externalExecutionEnabled, false);
  assert.equal(engine.transitionOrder(order.orderId, "PLANNED", "operator").status, "PLANNED");
  assert.equal(engine.status().paymentEnabled, false);
  assert.ok(engine.auditTrail().length >= 6);
  console.log("Terra commercial company engine tests passed.");
})().catch(error => { console.error(error); process.exitCode = 1; });
